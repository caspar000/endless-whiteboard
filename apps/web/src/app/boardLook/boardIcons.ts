/**
 * The icons a board can wear on its tab, its sidebar row and its card: a hand-picked few hundred of
 * Lucide's, in groups, each with the words someone might search for ("gym" finds the dumbbell). Picked
 * rather than all of Lucide so the bundle carries only these, and so a search finds what a person means
 * rather than every icon whose name happens to contain the letters.
 *
 * A board stores the icon's `name`, so a name here is stored data: rename one and boards wearing it go
 * back to no icon. Add freely; remove or rename only with that in mind.
 */
export interface BoardIcon {
	name: string
	Icon: LucideIcon
	group: string
	/** What it is called, then what else someone might type to find it. */
	words: string
}

