export const BOARD_ICON_GROUPS: readonly string[] = GROUPS.map(([group]) => group)

export const BOARD_ICONS: readonly BoardIcon[] = GROUPS.flatMap(([group, entries]) =>
	entries.map(([name, Icon, words]) => ({ name, Icon, group, words: `${name.replace(/-/g, ' ')} ${words}` }))
)

const byName = new Map(BOARD_ICONS.map((icon) => [icon.name, icon]))

/** The icon a board names, or `undefined` for none, or one this version no longer has. */
export const boardIcon = (name: string | undefined): BoardIcon | undefined => (name ? byName.get(name) : undefined)

/**
 * The icons whose words start with every word typed, in catalogue order: "fit" finds the dumbbell,
 * "sea boat" the sailboat. An empty query is every icon.
 */
export function searchBoardIcons(query: string): readonly BoardIcon[] {
	const terms = query.toLowerCase().split(/\s+/).filter(Boolean)
	if (!terms.length) return BOARD_ICONS
	return BOARD_ICONS.filter((icon) => {
		const words = icon.words.split(' ')
		return terms.every((term) => words.some((word) => word.startsWith(term)))
	})
}
